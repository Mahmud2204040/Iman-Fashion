function translateDynamicError(value) {
  let match = /^Item (\d+): (product is unavailable|quantity must be a whole number greater than zero|selling price must be greater than zero|repeat product uses a different price)\.$/.exec(value);
  if (match) {
    const detail = {
      'product is unavailable': 'পণ্যটি পাওয়া যাচ্ছে না',
      'quantity must be a whole number greater than zero': 'পরিমাণ 0-এর বেশি পূর্ণসংখ্যা হতে হবে',
      'selling price must be greater than zero': 'বিক্রয়মূল্য 0-এর বেশি হতে হবে',
      'repeat product uses a different price': 'একই পণ্যের জন্য ভিন্ন দাম দেওয়া হয়েছে',
    }[match[2]];
    return `আইটেম ${match[1]}: ${detail}।`;
  }
  match = /^Child #(\d+): (name is required\. Fill the row or remove it|initial class and school are required|registered date is invalid)\.$/.exec(value);
  if (match) {
    const detail = {
      'name is required. Fill the row or remove it': 'নাম লিখুন অথবা সারিটি মুছুন',
      'initial class and school are required': 'প্রাথমিক শ্রেণি ও বিদ্যালয় প্রয়োজন',
      'registered date is invalid': 'নিবন্ধনের তারিখ সঠিক নয়',
    }[match[2]];
    return `শিশু ${match[1]}: ${detail}।`;
  }
  match = /^Line item #(\d+) is missing a name\.$/.exec(value);
  if (match) return `লাইন ${match[1]}-এর নাম প্রয়োজন।`;
  match = /^Line item "(.+)" needs a (quantity greater than 0|non-negative unit price)\.$/.exec(value);
  if (match) return `"${match[1]}" লাইনে ${match[2] === 'quantity greater than 0' ? 'পরিমাণ 0-এর বেশি' : 'একক দাম 0 বা তার বেশি'} হতে হবে।`;
  match = /^(.+): only (\d+) item\(s\) in stock\.$/.exec(value);
  if (match) return `${match[1]}: স্টকে মাত্র ${match[2]}টি আছে।`;
  match = /^Payment exceeds the remaining balance \((৳[\d,.]+)\)\.$/.exec(value);
  if (match) return `পেমেন্ট অবশিষ্ট বকেয়া (${match[1]}) ছাড়িয়ে গেছে।`;
  match = /^Adjustment would drive stock negative \(current (-?\d+), change (-?\d+)\)\.$/.exec(value);
  if (match) return `সমন্বয় করলে স্টক ঋণাত্মক হবে (বর্তমান ${match[1]}, পরিবর্তন ${match[2]})।`;
  return null;
}

function initialLanguage() {
  let value = 'en';
  try { value = localStorage.getItem(STORAGE_KEY) === 'bn' ? 'bn' : 'en'; } catch { /* storage is optional */ }
  setUiLanguage(value);
  return value;
}

export function LocaleProvider({ children }) {
  const [language, setLanguage] = useState(initialLanguage);
  useEffect(() => {
    setUiLanguage(language);
    document.documentElement.lang = language;
    try { localStorage.setItem(STORAGE_KEY, language); } catch { /* storage is optional */ }
  }, [language]);
  const changeLanguage = useCallback((value) => {
    const next = value === 'bn' ? 'bn' : 'en';
    setUiLanguage(next);
    setLanguage(next);
  }, []);
  const t = useCallback((value) => language === 'bn' ? BN[value] || translateDynamicError(value) || value : value, [language]);
  const context = useMemo(() => ({ language, changeLanguage, t }), [language, changeLanguage, t]);
  return <LocaleContext.Provider value={context}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  const context = useContext(LocaleContext);
  if (!context) throw new Error('useLocale must be used inside LocaleProvider.');
  return context;
}
